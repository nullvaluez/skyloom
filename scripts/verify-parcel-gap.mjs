import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const src = readFileSync(new URL('../lib/fly/parcel-gap.js', import.meta.url), 'utf8');
const { parcelGapDecision, parcelGapSourceReady, parcelGapSupported } = await import(`data:text/javascript;base64,${Buffer.from(src).toString('base64')}`);
const anchors = Array.from({length:8}, (_,i)=>({x:i*20,z:i%2*30}));
assert.equal(parcelGapSupported(anchors,0,0,1.31),true,'Contiguous residential support');
assert.equal(parcelGapSupported(anchors.slice(0,2),0,0,1.31),false,'Sparse supported land stays sparse');
assert.equal(parcelGapSupported([],0,0,1.31),false,'No parcels means no homes');
assert.equal(parcelGapDecision(undefined,{ready:true,supported:true,columns:0}),true,'Resolved clear residential gap');
assert.equal(parcelGapDecision(undefined,{ready:false,supported:true,columns:0}),false,'A streaming lapse cannot create a gap');
assert.equal(parcelGapDecision(false,{ready:true,supported:true,columns:0}),false,'Mapped veto survives loss of source');
assert.equal(parcelGapDecision(true,{ready:false,supported:true,columns:0}),true,'Known gap survives a transient streaming lapse');
assert.equal(parcelGapDecision(true,{ready:true,supported:true,columns:1}),false,'Real mapped buildings always win');
const rows = new Map();
for(let x=8191;x<=8192;x++)for(let z=8191;z<=8192;z++)rows.set(`14/${x}/${z}`,{state:'ready',readyAt:10,coarse:false,badFrac:0});
assert.equal(parcelGapSourceReady(rows,0,0,600,20),true,'All local tiles settled');
assert.equal(parcelGapSourceReady(rows,0,0,600,11),false,'Birth is not complete');
rows.get('14/8191/8191').state='error';
assert.equal(parcelGapSourceReady(rows,0,0,600,20),false,'Error is not empty residential ground');
rows.get('14/8191/8191').state='ready';rows.get('14/8191/8191').coarse=true;
assert.equal(parcelGapSourceReady(rows,0,0,600,20),false,'Coarse drape is not evidence');
console.log('PARCEL GAP: PASS (12 safety and evidence cases)');
