#!/usr/bin/env node
/**
 * build-tile-worker — Round 24 (A PACE).
 *
 * Stringifies the READABLE worker source under
 * `lib/fly/vendor/three-tile/workers/` into a JS module the vendored bundle can
 * splice into three-tile's own inline DEM worker.
 *
 *   node scripts/build-tile-worker.mjs          # write the built file
 *   node scripts/build-tile-worker.mjs --check  # fail if it is out of date
 *
 * WHY THIS EXISTS. three-tile ships its DEM workers as minified source strings
 * turned into Blob URLs at runtime. Hand-editing an 8 KB minified string is how
 * a vendored patch becomes unreviewable, so VENDOR.md forbids it: worker-side
 * changes are authored in a real file here and re-stringified by this script.
 * `--check` is run by scripts/verify-vendor-three-tile.mjs, so a source edit
 * that was never rebuilt goes red instead of shipping stale.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'lib/fly/vendor/three-tile/workers');
const SOURCES = [{ src: 'skirt-tail.src.js', out: 'skirt-tail.built.js', name: 'R24_WORKER_SKIRT_TAIL' }];
const CHECK = process.argv.includes('--check');

const header = (srcName) => `// GENERATED by scripts/build-tile-worker.mjs from ${srcName} — DO NOT EDIT.
// Edit the .src.js next to this file and re-run the script. The vendored
// bundle splices this string into three-tile's inline DEM worker source
// (lib/fly/vendor/three-tile/VENDOR.md, PATCH 5).
`;

let stale = 0;
for (const { src, out, name } of SOURCES) {
  const srcPath = path.join(dir, src);
  const outPath = path.join(dir, out);
  const body = readFileSync(srcPath, 'utf8');
  const text = `${header(src)}export const ${name} = ${JSON.stringify(body)};\n`;
  const prev = existsSync(outPath) ? readFileSync(outPath, 'utf8') : null;
  if (prev === text) {
    console.log(`  up to date  ${out}`);
    continue;
  }
  if (CHECK) {
    stale++;
    console.log(`  STALE       ${out} — re-run: node scripts/build-tile-worker.mjs`);
    continue;
  }
  writeFileSync(outPath, text);
  console.log(`  wrote       ${out}  (${body.length} chars of source)`);
}
if (CHECK && stale) process.exit(1);
