// Rebuild the three original airframes, their presentation contract and receipts.
// --manifest-only refreshes metadata after an individual model builder is run.
import fs from 'node:fs';
import { spawnSync } from 'node:child_process';
const ids = ['f35','c17','concorde'];
const definitions = [];
for (const id of ids) {
  if (!process.argv.includes('--manifest-only')) {
    const child = spawnSync(process.execPath, [`scripts/build-${id}.mjs`], { stdio:'inherit' });
    if (child.status !== 0) throw Error(`${id} build failed`);
  }
  const mod = await import(`./build-${id}.mjs`);
  definitions.push(mod.definition ?? mod.DEF);
}
fs.writeFileSync('lib/fly/special-aircraft.mjs',
  '// Generated by scripts/build-player-expansion.mjs from the authored model definitions.\n' +
  '// Metres, +Y up, nose -Z; no model-building code enters the browser bundle.\n' +
  `export const SPECIAL_AIRCRAFT = ${JSON.stringify(Object.fromEntries(definitions.map(d=>[d.id,d])),null,2)};\n`);
const file = 'public/models/adventure-fleet-v1.json';
const kept = JSON.parse(fs.readFileSync(file,'utf8')).filter(r=>r.id&&!ids.includes(r.id));
const fresh = ids.flatMap(id=>{
  const metrics=JSON.parse(fs.readFileSync(`public/models/${id}-metrics.json`,'utf8'));
  return Array.isArray(metrics)?metrics:metrics.rows;
})
  .map(({id,lod,url,triangles,draws,bytes})=>({id,lod,url,triangles,draws,bytes}));
fs.writeFileSync(file,JSON.stringify([...kept,...fresh],null,2)+'\n');
console.log('Updated aircraft presentation and receipts:', ids.join(', '));
