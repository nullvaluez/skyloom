import assert from 'node:assert/strict';
import { ResidentReliefBackfill } from '../lib/fly/relief-backfill.js';
const tick = () => new Promise((r) => setImmediate(r));
const tile = () => ({ model: { geometry: { userData: {} } } });
const pending = [];
const load = () => new Promise((resolve, reject) => pending.push({ resolve, reject }));
const commit = (t, g, bytes) => { g.userData.r25Relief = bytes; return true; };
let now = 100;
const q = new ResidentReliefBackfill({ now: () => now });
const a = tile(), b = tile(), c = tile();
assert(q.request(a, load, commit));
assert(q.request(b, load, commit));
assert(!q.request(c, load, commit));
assert(!q.request(a, load, commit));
await tick();
pending.shift().resolve(new Uint8Array([1, 2]));
await tick();
assert.deepEqual([...a.model.geometry.userData.r25Relief], [1, 2]);
assert(!q.request(a, load, commit));
q.reset();
assert(q.request(c, load, commit));
assert(!q.request(tile(), load, commit));
await tick();
pending.shift().resolve(new Uint8Array([3, 4]));
await tick();
assert.equal(b.model.geometry.userData.r25Relief, undefined, 'profile change discards stale completion');
c.model.geometry = { userData: {} };
pending.shift().resolve(new Uint8Array([5, 6]));
await tick();
assert.equal(c.model.geometry.userData.r25Relief, undefined, 'replacement geometry is never overwritten');
assert(q.request(b, load, commit));
await tick();
pending.shift().reject(new Error('offline'));
await tick();
assert(!q.request(b, load, commit), 'failures back off');
now += 30001;
assert(q.request(b, load, () => false));
await tick();
pending.shift().resolve(new Uint8Array([1, 2]));
await tick();
assert.equal(b.model.geometry.userData.r25Relief, undefined, 'evicted tile cannot commit');
assert.equal(q.stats.peak, 2);
assert.equal(q.stats.completed, 1);
assert.equal(q.stats.discarded, 3);
assert.equal(q.stats.failed, 1);
assert.equal(q.stats.active, 0);
console.log('PASS: resident fill, deduplication, bounded concurrency, rapid toggles, geometry replacement, eviction, retry and disposal');
